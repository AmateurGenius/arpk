#[test]
fn golden_vectors_match_independent_implementation() {
    let k = Sha3Keccak;
    let domain = Domain {
        name: "ARPK".to_string(),
        version: "1".to_string(),
        salt: [0u8; 32],
    };
    for (i, v) in VECTORS.iter().enumerate() {
        let mut domain = domain.clone();
        domain.salt = v.salt;
        let receipt = Receipt {
            agent_id: v.agent_id,
            session_id: v.session_id,
            class: v.class,
            action_hash: v.action_hash,
            manifest_hash: v.manifest_hash,
            context_hash: v.context_hash,
            verdict: v.verdict,
            nonce: v.nonce,
            issued_ms: v.issued_ms,
            expiry_ms: v.expiry_ms,
        };
        let got = digest(&k, &domain, &receipt);
        assert_eq!(got, v.expected, "vector {i} digest mismatch");
    }
}

#[test]
fn domain_separator_depends_on_salt() {
    let k = Sha3Keccak;
    let a = Domain {
        name: "ARPK".to_string(),
        version: "1".to_string(),
        salt: [0u8; 32],
    };
    let mut b = a.clone();
    b.salt = [1u8; 32];
    let r = Receipt {
        agent_id: [0u8; 32],
        session_id: [0u8; 16],
        class: 1,
        action_hash: [0u8; 32],
        manifest_hash: [0u8; 32],
        context_hash: [0u8; 32],
        verdict: 1,
        nonce: [0u8; 16],
        issued_ms: 1,
        expiry_ms: 2,
    };
    assert_ne!(digest(&k, &a, &r), digest(&k, &b, &r));
}
